#!/usr/bin/env python3
"""Reconcile checkov and tfsec JSON output into a per-control, per-resource table.

Usage: reconcile.py CHECKOV_JSON TFSEC_JSON > docs/security/iac-findings-reconciled.md
"""
import collections
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from crosswalk import CONCEPTS

TFSEC_SEV_RANK = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3}


def norm_resource(resource):
    parts = resource.split(".")
    if parts[0] in ("data", "module"):
        return ".".join(parts[:3])
    return ".".join(parts[:2])


def norm_path(path):
    path = path.replace("\\", "/")
    if "/terraform/" in path:
        path = path.split("/terraform/", 1)[1]
    return path.lstrip("/")


def load_checkov(path):
    with open(path) as fh:
        data = json.load(fh)
    blocks = data if isinstance(data, list) else [data]
    out = []
    for blk in blocks:
        for f in blk["results"]["failed_checks"]:
            res = f["resource"]
            if blk["check_type"] == "secrets":
                res = "(secret)"
            out.append((f["check_id"], norm_path(f["file_path"]), norm_resource(res) if res != "(secret)" else res))
    return out


def load_tfsec(path):
    with open(path) as fh:
        results = json.load(fh)["results"] or []
    out = []
    for f in results:
        out.append((f["long_id"], norm_path(f["location"]["filename"]), norm_resource(f["resource"]), f["severity"]))
    return out


def main(ck_path, tf_path):
    ck = load_checkov(ck_path)
    tf = load_tfsec(tf_path)
    ck_map = {rid: c for c in CONCEPTS for rid in c[3]}
    tf_map = {rid: c for c in CONCEPTS for rid in c[4]}

    rows = collections.defaultdict(lambda: {"ck": set(), "tf": set(), "sev": set()})
    unmapped_ck, unmapped_tf = collections.Counter(), collections.Counter()
    for rid, f, r in ck:
        c = ck_map.get(rid)
        if c is None:
            unmapped_ck[rid] += 1
            continue
        key = (c[0], f, r)
        rows[key]["ck"].add(rid)
    for rid, f, r, sev in tf:
        c = tf_map.get(rid)
        if c is None:
            unmapped_tf[(rid, sev)] += 1
            continue
        key = (c[0], f, r)
        rows[key]["tf"].add(rid)
        rows[key]["sev"].add(sev)

    by_concept = collections.defaultdict(list)
    for (concept, f, r), v in rows.items():
        by_concept[concept].append((f, r, v))

    totals = collections.Counter()
    print("# Reconciled checkov + tfsec findings (generated)\n")
    print("Generated by `tools/iac-scan/reconcile.py`. Do not edit by hand; see "
          "`docs/security/iac-remediation-backlog.md` for the prioritized backlog.\n")
    print(f"Inputs: checkov {len(ck)} failed checks, tfsec {len(tf)} results.\n")
    summary = []
    for key, prio, title, _, _ in CONCEPTS:
        items = sorted(by_concept.get(key, []))
        if not items:
            continue
        both = sum(1 for _, _, v in items if v["ck"] and v["tf"])
        ck_only = sum(1 for _, _, v in items if v["ck"] and not v["tf"])
        tf_only = sum(1 for _, _, v in items if v["tf"] and not v["ck"])
        totals.update(both=both, ck_only=ck_only, tf_only=tf_only)
        summary.append((prio, key, title, len(items), both, ck_only, tf_only))
        print(f"## P{prio} `{key}` — {title}\n")
        print(f"{len(items)} resource(s): {both} both, {ck_only} checkov-only, {tf_only} tfsec-only.\n")
        print("| File | Resource | Agreement | checkov | tfsec (severity) |")
        print("|---|---|---|---|---|")
        for f, r, v in items:
            agree = "both" if v["ck"] and v["tf"] else ("checkov only" if v["ck"] else "tfsec only")
            sev = "/".join(sorted(v["sev"], key=TFSEC_SEV_RANK.get))
            tfcell = ", ".join(sorted(v["tf"])) + (f" ({sev})" if sev else "")
            print(f"| {f} | `{r}` | {agree} | {', '.join(sorted(v['ck']))} | {tfcell} |")
        print()

    print("## Summary by control\n")
    print("| Priority | Control | Resources | Both | checkov only | tfsec only |")
    print("|---|---|---|---|---|---|")
    for prio, key, title, n, b, c, t in sorted(summary):
        print(f"| P{prio} | `{key}` | {n} | {b} | {c} | {t} |")
    print(f"| | **Total** | {sum(s[3] for s in summary)} | {totals['both']} | {totals['ck_only']} | {totals['tf_only']} |\n")

    print("## Rules not in the crosswalk\n")
    print("Tool-specific checks with no counterpart in the other tool (treated as P3 unless called out in the backlog).\n")
    print("| Tool | Rule | Count |")
    print("|---|---|---|")
    for rid, n in sorted(unmapped_ck.items()):
        print(f"| checkov | {rid} | {n} |")
    for (rid, sev), n in sorted(unmapped_tf.items()):
        print(f"| tfsec | {rid} ({sev}) | {n} |")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
